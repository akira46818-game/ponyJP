const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const scope={};vm.runInNewContext(fs.readFileSync('academy/market-gifts.js','utf8'),scope);
const {createStore,cards}=scope.MarketGiftStore;
const memory=new Map(),storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
let draws=0;const store=createStore(storage,()=>{draws++;return .99;});
const ticket=store.grant('first-game',1);
assert.equal(store.grant('first-game',1).id,ticket.id);
assert.equal(store.pending().length,1,'repeated completion must not issue another ticket');
assert.throws(()=>store.claim('invented-id'));
const award=store.claim(ticket.id);
assert.equal(award.card,'tespero');assert.equal(store.pending().length,0);
assert.equal(store.claim(ticket.id).card,award.card);assert.equal(draws,1,'retry must not redraw');
const reloaded=createStore(storage,()=>{throw Error('must not redraw after reload');});
assert.equal(reloaded.claim(ticket.id).card,award.card);
store.grant('first-game',2);store.grant('new-game',1);
assert.equal(store.pending().length,2,'next day and explicit restart get distinct tickets');
assert.equal(cards.reduce((sum,c)=>sum+c.weight,0),100);
const noxStore=createStore(storage,()=>.1),noxTicket=noxStore.grant('nox-regression',1),noxAward=noxStore.claim(noxTicket.id);
assert.equal(noxAward.card,'nox');
const savedNox=reloaded.claim(noxTicket.id),noxMetadata=cards.find(c=>c.id===savedNox.card);
assert.equal(noxMetadata.name,'ノクス');assert.equal(noxMetadata.file,'nox.png','the corrected display name must keep existing card ownership and artwork');
const broken=createStore({getItem:()=>null,setItem:()=>{throw Error('quota');}});
assert.throws(()=>broken.grant('game',1),/quota/,'failed storage must not report a saved gift');
console.log('PASS: clear tickets, replay, recovery, random weights, storage failure');
