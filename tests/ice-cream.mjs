import assert from 'node:assert/strict';
import { CUSTOMERS, FLAVORS, createSession, restoreSession, checkOrder, serve, addScoop, changeCustomer } from '../academy/ice-cream/model.mjs';
const state=createSession('test-round');
assert.equal(CUSTOMERS.length,6);
assert.deepEqual(CUSTOMERS.map(c=>c.id),['lumina','flare','aqua','cat','terra','storm']);
assert.equal(serve(state).ok,false,'Empty cones cannot earn progress');
addScoop(state,'chocolate');addScoop(state,'vanilla');state.topping='star';
assert.equal(serve(state).ok,false,'Wrong order stays editable');
assert.equal(state.completed.length,0);
changeCustomer(state,'lumina');
for(const c of CUSTOMERS){
  changeCustomer(state,c.id);
  for(const id of c.order)assert.equal(addScoop(state,id),true);
  assert.equal(addScoop(state,'vanilla'),false,'Order cannot overflow');
  assert.equal(serve(state).ok,false,'Requested decoration matters');
  state.topping=c.topping;
  assert.equal(checkOrder(state).ok,true);
  assert.equal(serve(state).ok,true);
  const count=state.completed.length;
  assert.equal(serve(state).ok,false,'Repeat serve cannot count twice');
  assert.equal(state.completed.length,count);
}
assert.equal(state.completed.length,6);
const restored=restoreSession(JSON.parse(JSON.stringify(state)),'new');
assert.equal(restored.roundId,'test-round');
assert.deepEqual(restored.completed,state.completed);
assert.equal(restored.served,true);
changeCustomer(restored,'lumina');
assert.equal(restored.served,true);
assert.deepEqual(restored.scoops,['strawberry','vanilla'],'Completed customers display their delivered ice');
const free=createSession('free');free.mode='free';
for(let i=0;i<4;i++)assert.equal(addScoop(free,FLAVORS[i].id),true);
assert.equal(addScoop(free,'grape'),false);
assert.equal(serve(free).ok,true);
assert.equal(free.completed.length,0,'Creative mode does not issue clear progress');
const invalid=restoreSession({version:1,roundId:'saved',customer:'missing',completed:['lumina','lumina','unknown'],scoops:['fake','soda'],topping:'fake'},'new');
assert.deepEqual(invalid.completed,['lumina']);
assert.deepEqual(invalid.scoops,['soda']);
assert.equal(invalid.topping,null);
assert.equal(invalid.customer,'lumina');
console.log('PASS: six customers, order validation, limits, replay protection, save recovery and free mode');
